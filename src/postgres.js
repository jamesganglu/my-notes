// Exports the notes database as PostgreSQL SQL: the schema alone, or the schema plus data.
// The Postgres schema is written by hand (not translated from SQLite) so each column gets
// the idiomatic Postgres type; keep it in step with the tables in db.js.

const quote = (value) => {
  if (value == null) return 'NULL';
  // Postgres text can't hold NUL bytes; standard_conforming_strings makes backslashes literal.
  return `'${String(value).replace(/\0/g, '').replace(/'/g, "''")}'`;
};

// SQLite datetime('now') values are UTC "YYYY-MM-DD HH:MM:SS".
const timestamp = (value) => (value ? quote(`${value}+00`) : 'NULL');

function schemaSql(noteTypes) {
  const types = noteTypes.map(quote).join(', ');
  return `CREATE TABLE notes (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title      TEXT NOT NULL,
  type       TEXT NOT NULL CHECK (type IN (${types})),
  content    TEXT NOT NULL DEFAULT '',
  category   TEXT NOT NULL DEFAULT '',
  language   TEXT,
  username   TEXT,
  url        TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

COMMENT ON COLUMN notes.content IS 'Plain text for text/markdown/code; JSON for changelog/todo; AES-256-GCM ciphertext ("enc:iv:tag:data", base64) for password';
COMMENT ON COLUMN notes.language IS 'Code notes only';
COMMENT ON COLUMN notes.username IS 'Password notes only';
COMMENT ON COLUMN notes.url IS 'Password notes only';

CREATE INDEX idx_notes_category ON notes (category);
CREATE INDEX idx_notes_type ON notes (type);

CREATE TABLE tags (
  id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL
);

-- Tag names are unique regardless of case (SQLite: UNIQUE COLLATE NOCASE).
CREATE UNIQUE INDEX tags_name_lower_key ON tags (lower(name));

CREATE TABLE note_tags (
  note_id BIGINT NOT NULL REFERENCES notes (id) ON DELETE CASCADE,
  tag_id  BIGINT NOT NULL REFERENCES tags (id) ON DELETE CASCADE,
  PRIMARY KEY (note_id, tag_id)
);

CREATE INDEX idx_note_tags_tag ON note_tags (tag_id);
`;
}

function header(kind) {
  return `-- Note Taker ${kind} for PostgreSQL
-- Generated ${new Date().toISOString()}
-- Run against an empty database, e.g.: psql -d mydb -f this-file.sql

SET client_encoding = 'UTF8';
SET standard_conforming_strings = on;

`;
}

// Multi-row INSERTs, in batches so no single statement gets huge.
function insertSql(table, columns, rows, toValues, batchSize = 500) {
  if (!rows.length) return `-- (no rows in ${table})\n`;
  const out = [];
  for (let i = 0; i < rows.length; i += batchSize) {
    const values = rows.slice(i, i + batchSize).map((r) => `  (${toValues(r).join(', ')})`);
    out.push(`INSERT INTO ${table} (${columns.join(', ')}) VALUES\n${values.join(',\n')};`);
  }
  return out.join('\n\n') + '\n';
}

// Continue identity numbering after the highest id ever used (SQLite AUTOINCREMENT
// never reuses ids, so the sqlite_sequence high-water mark is honoured too).
function sequenceSql(table, next) {
  return `SELECT setval(pg_get_serial_sequence('${table}', 'id'), ${next}, false);\n`;
}

function postgresSchema(noteTypes) {
  return header('schema') + schemaSql(noteTypes);
}

function postgresDump(db, noteTypes) {
  const notes = db.prepare('SELECT * FROM notes ORDER BY id').all();
  const tags = db.prepare('SELECT * FROM tags ORDER BY id').all();
  const noteTags = db.prepare('SELECT * FROM note_tags ORDER BY note_id, tag_id').all();
  const nextId = (table) => {
    const seq = db.prepare('SELECT seq FROM sqlite_sequence WHERE name = ?').pluck().get(table);
    const max = db.prepare(`SELECT MAX(id) FROM ${table}`).pluck().get();
    return Math.max(seq || 0, max || 0) + 1;
  };

  return header('dump') + `BEGIN;

${schemaSql(noteTypes)}
-- Data: ${notes.length} notes, ${tags.length} tags, ${noteTags.length} note/tag links.
-- Password note content is exported encrypted, exactly as stored.

${insertSql('notes',
    ['id', 'title', 'type', 'content', 'category', 'language', 'username', 'url', 'created_at', 'updated_at'],
    notes,
    (n) => [n.id, quote(n.title), quote(n.type), quote(n.content), quote(n.category), quote(n.language),
      quote(n.username), quote(n.url), timestamp(n.created_at), timestamp(n.updated_at)])}
${insertSql('tags', ['id', 'name'], tags, (t) => [t.id, quote(t.name)])}
${insertSql('note_tags', ['note_id', 'tag_id'], noteTags, (nt) => [nt.note_id, nt.tag_id])}
${sequenceSql('notes', nextId('notes'))}${sequenceSql('tags', nextId('tags'))}
COMMIT;
`;
}

module.exports = { postgresSchema, postgresDump };
